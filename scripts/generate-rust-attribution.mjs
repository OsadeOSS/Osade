#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

/**
 * This file writes attribution for the crates inside the vendored runtime binary; their names are
 * the crates' own. The runtime itself is attributed by name in THIRD-PARTY-NOTICES.md.
 *
 * Rust crate attribution for the substrate binary Osade ships.
 *
 * Osade distributes a compiled the substrate, so the substrate's dependency tree is redistributed with it and
 * every crate's licence has to be reproduced. `cargo-about` is the usual tool; this exists
 * because it is not installed and installing a global Rust tool to satisfy a build step is a
 * worse dependency than reading the two files that already pin the answer.
 *
 * Input is the **pinned** `backend/Cargo.lock` and the local cargo registry — the same source
 * cargo built from. Nothing is inferred: a crate whose licence cannot be read from its own
 * `Cargo.toml` is listed as unresolved rather than guessed at, because a guessed licence in an
 * attribution file is worse than an admitted gap.
 *
 *   node scripts/generate-rust-attribution.mjs [--check]
 *
 * `--check` fails when the generated text differs from what is committed, so the file cannot
 * drift from the lock without CI noticing.
 */

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const LOCK = join(ROOT, 'backend', 'Cargo.lock');
const OUT = join(ROOT, 'vendor', 'runtime', '0.8.2-p20', 'RUST-CRATES.md');

/**
 * Crates with no `source` are the runtime's own or path dependencies — not third party.
 *
 * Line endings are normalised first: `backend/Cargo.lock` is CRLF on a Windows checkout, and a
 * parser that only knows `\n` silently reports zero crates, which looks exactly like a project
 * with no dependencies.
 */
function readLock(raw) {
  const text = raw.replace(/\r\n/g, '\n');
  const packages = [];
  for (const block of text.split(/\n\[\[package\]\]\n/).slice(1)) {
    const name = /^name = "(.+)"$/m.exec(block)?.[1];
    const version = /^version = "(.+)"$/m.exec(block)?.[1];
    const source = /^source = "(.+)"$/m.exec(block)?.[1];
    if (name && version && source) packages.push({ name, version });
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

/** CRLF in, LF out. A parser that only knows LF reports a lockfile as empty. */
function normalise(text) {
  return text.split(String.fromCharCode(13)).join(String.fromCharCode(10));
}

function registryRoots() {
  const base = join(homedir(), '.cargo', 'registry', 'src');
  if (!existsSync(base)) return [];
  return readdirSync(base).map((dir) => join(base, dir));
}

/**
 * The `license` field from a crate's own manifest.
 *
 * `license-file` (rather than an SPDX expression) is reported as such: it means the crate ships
 * bespoke terms that a human has to read, which is exactly the case that must not be silently
 * folded into a bucket.
 */
function licenseFor(roots, { name, version }) {
  for (const root of roots) {
    const manifest = join(root, `${name}-${version}`, 'Cargo.toml');
    if (!existsSync(manifest)) continue;
    const text = normalise(readFileSync(manifest, 'utf8'));
    const spdx = /^license\s*=\s*"(.+)"$/m.exec(text)?.[1];
    if (spdx) return { spdx };
    const file = /^license-file\s*=\s*"(.+)"$/m.exec(text)?.[1];
    if (file) return { spdx: null, licenseFile: file };
    return { spdx: null };
  }
  return null;
}

function render(groups, unresolved, total) {
  const lines = [
    '# Rust crates in the runtime binary',
    '',
    'Generated by `scripts/generate-rust-attribution.mjs` from the pinned `backend/Cargo.lock`.',
    'Do not edit by hand — run the script.',
    '',
    `${total} third-party crates, grouped by the licence each declares in its own \`Cargo.toml\`.`,
    'Crates with no `source` in the lockfile are the runtime\'s own or path dependencies and are not',
    'listed here.',
    '',
  ];

  for (const [spdx, crates] of [...groups].sort((a, b) => b[1].length - a[1].length)) {
    lines.push(`## ${spdx}`, '', `${crates.length} crate${crates.length === 1 ? '' : 's'}:`, '');
    lines.push(crates.map((c) => `\`${c.name} ${c.version}\``).join(', '), '');
  }

  if (unresolved.length > 0) {
    lines.push(
      '## Unresolved',
      '',
      'These could not be read from the local cargo registry, so their licence is **unknown**',
      'rather than assumed. Run `cargo fetch --manifest-path backend/Cargo.toml` and regenerate;',
      'anything still here needs a human before release.',
      '',
      unresolved.map((c) => `- \`${c.name} ${c.version}\``).join('\n'),
      '',
    );
  }

  lines.push(
    '## Not covered here',
    '',
    '- **libghostty-vt** and **portable-pty** are vendored into `backend/vendor/` rather than',
    '  resolved from crates.io, and carry their own patches. See the `.patches.md` files beside',
    '  them.',
    '- The runtime binary itself is Apache-2.0; see `LICENSE` in this directory and THIRD-PARTY-NOTICES.md.',
    '',
  );

  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const packages = readLock(readFileSync(LOCK, 'utf8'));
  const roots = registryRoots();

  const groups = new Map();
  const unresolved = [];

  for (const pkg of packages) {
    const found = licenseFor(roots, pkg);
    const spdx = found?.spdx ?? (found?.licenseFile ? `custom: ${found.licenseFile}` : null);
    if (!spdx) {
      unresolved.push(pkg);
      continue;
    }
    if (!groups.has(spdx)) groups.set(spdx, []);
    groups.get(spdx).push(pkg);
  }

  const text = render(groups, unresolved, packages.length);

  if (check) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      process.stderr.write(
        'RUST-CRATES.md is out of date with backend/Cargo.lock.\n' +
          'Run: node scripts/generate-rust-attribution.mjs\n',
      );
      process.exit(1);
    }
    process.stdout.write(`RUST-CRATES.md matches the lock (${packages.length} crates).\n`);
    return;
  }

  writeFileSync(OUT, text);
  process.stdout.write(
    `wrote ${OUT}\n  ${packages.length} crates, ${groups.size} licences, ` +
      `${unresolved.length} unresolved\n`,
  );
}

main();
